const id = new URLSearchParams(window.location.search).get("id");
const item = announcements[id];
const content = document.getElementById("announcement-content");
const notFound = document.getElementById("not-found");

function renderInformation(rows) {
  if (!rows?.length) return;
  const section = document.getElementById("event-section");
  const list = document.getElementById("event-information");
  rows.forEach(([label, value]) => {
    const row = document.createElement("div");
    const dt = document.createElement("dt");
    const dd = document.createElement("dd");
    dt.textContent = label;
    dd.textContent = value;
    row.append(dt, dd);
    list.append(row);
  });
  section.hidden = false;
}

function renderRequirements(requirements) {
  if (!requirements?.length) return;
  const section = document.getElementById("requirements-section");
  const list = document.getElementById("requirements-content");
  requirements.forEach((requirement) => {
    const item = document.createElement("li");
    item.textContent = requirement;
    list.append(item);
  });
  section.hidden = false;
}

function renderGallery(images) {
  const featured = document.getElementById("featured-image");
  const thumbs = document.getElementById("gallery-thumbnails");
  const counter = document.getElementById("image-counter");
  const lightbox = document.getElementById("image-lightbox");
  const lightboxImage = document.getElementById("lightbox-image");
  const lightboxCaption = document.getElementById("lightbox-caption");
  const prev = document.getElementById("gallery-previous");
  const next = document.getElementById("gallery-next");
  let active = 0;

  function show(index) {
    active = (index + images.length) % images.length;
    const image = images[active];
    featured.src = image.src;
    featured.alt = image.alt;
    lightboxImage.src = image.src;
    lightboxImage.alt = image.alt;
    lightboxCaption.textContent = image.alt;
    counter.textContent = `${active + 1} / ${images.length}`;
    [...thumbs.children].forEach((button, i) => {
      button.setAttribute("aria-pressed", String(i === active));
      if (i === active)
        button.scrollIntoView({ block: "nearest", inline: "nearest" });
    });
    prev.hidden = next.hidden = images.length < 2;
    document.getElementById("lightbox-previous").hidden = images.length < 2;
    document.getElementById("lightbox-next").hidden = images.length < 2;
  }

  images.forEach((image, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "gallery-thumbnail";
    button.setAttribute("aria-label", `Show image ${index + 1}`);
    button.setAttribute("aria-pressed", "false");
    const img = document.createElement("img");
    img.src = image.src;
    img.alt = "";
    img.loading = "lazy";
    button.append(img);
    button.addEventListener("click", () => show(index));
    thumbs.append(button);
  });
  prev.addEventListener("click", () => show(active - 1));
  next.addEventListener("click", () => show(active + 1));

  function openLightbox() {
    lightbox.hidden = false;
    document.body.style.overflow = "hidden";
    document.getElementById("lightbox-close").focus();
  }

  featured.addEventListener("click", openLightbox);
  featured.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      openLightbox();
    } else if (event.key === "ArrowLeft") {
      event.preventDefault();
      show(active - 1);
    } else if (event.key === "ArrowRight") {
      event.preventDefault();
      show(active + 1);
    }
  });
  document
    .getElementById("lightbox-previous")
    .addEventListener("click", () => show(active - 1));
  document
    .getElementById("lightbox-next")
    .addEventListener("click", () => show(active + 1));
  function close() {
    lightbox.hidden = true;
    document.body.style.overflow = "";
    featured.focus();
  }
  document.getElementById("lightbox-close").addEventListener("click", close);
  lightbox.addEventListener("click", (event) => {
    if (event.target === lightbox) close();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && !lightbox.hidden) close();
    if (event.key === "ArrowLeft" && !lightbox.hidden) show(active - 1);
    if (event.key === "ArrowRight" && !lightbox.hidden) show(active + 1);
  });
  show(0);
}

if (!item) {
  content.hidden = true;
  document.querySelector(".gallery-section").hidden = true;
  notFound.hidden = false;
} else {
  document.title = `${item.title} | SKConnect`;
  document.getElementById("breadcrumb-title").textContent = item.title;
  document.getElementById("announcement-category").textContent = item.category;
  document.getElementById("announcement-date").textContent =
    `Posted ${item.postedLabel}`;
  document.getElementById("announcement-date").dateTime = item.posted;
  document.getElementById("announcement-title").textContent = item.title;
  document.getElementById("announcement-summary").textContent = item.summary;
  document.getElementById("announcement-description").textContent =
    item.description;
  document.getElementById("sidebar-category").textContent = item.category;
  document.getElementById("sidebar-date").textContent = item.postedLabel;
  if (item.deadline) {
    document.getElementById("sidebar-deadline").textContent = item.deadline;
    document.getElementById("sidebar-deadline-row").hidden = false;
  }
  renderInformation(item.information || item.event);
  renderRequirements(item.requirements);
  renderGallery(item.images);
}
document.getElementById("footer-year").textContent = new Date().getFullYear();
